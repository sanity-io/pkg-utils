/**
 * A tsdown plugin for [Panda CSS](https://panda-css.com) libraries: the companion of the
 * official `@pandacss/vite` plugin for the `tsdown.config.ts` of packages published to npm.
 * Applications keep using `@pandacss/vite` in their `vite.config.ts`; this plugin replaces it in
 * the library build only.
 *
 * It loads the Panda config (`panda.config.ts`) with Panda's node driver, scans the sources the
 * config's `include`/`exclude` globs cover, rewrites their `css()`/`cva()`/pattern/recipe calls
 * into static class names with `@pandacss/transformer` (so the published JavaScript carries no
 * Panda runtime), and emits the generated stylesheet as a single `lightningcss`-optimized CSS
 * file — optionally lowered to the build's `target`, minified, injected into the entry chunks,
 * and published as a conditional `"./bundle.css"` export subpath, following the same
 * architecture (and option vocabulary) as `@tsdown/css` and
 * `@sanity/vanilla-extract-tsdown-plugin`.
 *
 * Like `@pandacss/vite`, it also runs Panda's codegen before the build starts, so the generated
 * `styled-system` directory the sources import is in sync with the config the stylesheet is
 * extracted with. Packages keep their `prepare` script (`panda codegen`) for the type checker,
 * the test runner and the editor, which need the artifacts before any build runs.
 * @public
 */
export function pandacssPlugin(options: Options = {}): PandacssPlugin {
  const fileName = normalizeFileName(options.fileName ?? DEFAULT_CSS_FILE_NAME)
  const minify = options.minify ?? false
  const transformEnabled = options.transform ?? true
  const codegenEnabled = options.codegen ?? true
  const lightningcss = options.lightningcss
  const {inject, exports: exportsCss, nodeCompat} = resolveCssExportOptions(options)

  /** The host-resolved default for the `target` option (e.g. tsdown's top-level `target`). */
  let contextTarget: string | string[] | undefined
  /** The consumer's package name, for the self-referential CSS import injected by `inject`. */
  let packageName: string | undefined
  /** The host-resolved default working directory (e.g. tsdown's `cwd`). */
  let contextCwd: string | undefined
  /** The bundler's working directory (rolldown's `cwd` input option), recorded by `options`. */
  let inputCwd: string | undefined
  /** The host-resolved output directory (tsdown's `outDir`), excluded from watching. */
  let contextOutDir: string | undefined

  /**
   * The Panda driver (config, compiler and source scanner), created once per plugin instance and
   * shared by the builds a host runs with it — tsdown runs one per output format.
   */
  let driverPromise: Promise<PandaDriver> | undefined
  let driver: PandaDriver | undefined
  let transformer: SourceTransformer | undefined
  let transformerCompiler: PandaDriver['compiler'] | undefined
  /** Whether a build already ran, so a later `buildStart` (watch mode) reloads the config. */
  let built = false
  /**
   * The codegen tsdown's `build:before` hook runs once for the builds of every format; when
   * set, the rolldown `options` hook leaves the first codegen to it.
   */
  let codegenBeforeBuilds: Promise<void> | undefined

  /**
   * The ids of the modules with Panda styles — rewritten by the transformer, or left to the
   * runtime (dynamic calls, or `transform: false`). Builds a host runs in parallel with a shared
   * plugin instance all add to it (module ids are stable), and `renderChunk` consults it per
   * output to decide which entry chunks import the CSS.
   */
  const pandaModules = new Set<string>()
  /** Diagnostics already reported, so repeated scans don't warn about the same thing again. */
  const reportedDiagnostics = new Set<string>()

  function resolveCwd(): string {
    // A relative `cwd` option is relative to the host's working directory, like tsdown's own
    // paths — which isn't necessarily the process's (tsdown's `cwd` option, workspaces).
    // Module ids are real paths, so a symlinked project root is resolved as well: the
    // transform filter and Panda's matcher then compare them like with like.
    const base = path.resolve(contextCwd ?? inputCwd ?? process.cwd())
    return realpathOrSelf(options.cwd === undefined ? base : path.resolve(base, options.cwd))
  }

  async function resolveDriver(cwd: string): Promise<PandaDriver> {
    driverPromise ??= createNodeDriver({cwd, configPath: options.configPath})
    driver = await driverPromise
    return driver
  }

  function runCodegen(currentDriver: PandaDriver): void {
    currentDriver.codegen(options.outdir === undefined ? undefined : {outdir: options.outdir})
  }

  function resolveTransformer(currentDriver: PandaDriver): SourceTransformer {
    // The compiler is swapped on a config reload, and the transformer is bound to one
    if (!transformer || transformerCompiler !== currentDriver.compiler) {
      transformer = createSourceTransformer(currentDriver.compiler)
      transformerCompiler = currentDriver.compiler
    }
    return transformer
  }

  function resolveTargets(): Targets | undefined {
    // Matching `@tsdown/css`: explicit `lightningcss.targets` win, then the esbuild-style
    // `target` (the option, falling back to the host-resolved context target) is converted.
    // Browserless targets (e.g. tsdown's common `target: 'node20'`, which speaks to the JS
    // runtime) convert to nothing, skipping syntax lowering — `@sanity/tsdown-config` layers
    // the `@sanity/browserslist-config` default on top through `lightningcss.targets`.
    if (lightningcss?.targets) return lightningcss.targets
    if (options.target === false) return undefined
    const target = options.target ?? contextTarget
    if (target === undefined) return undefined
    return esbuildTargetToLightningCSS(target)
  }

  function resolvePackageName(entryModuleId: string | null): string {
    // Prefer the host-provided package name (`api.setBuildContext`); otherwise, resolve the
    // package.json owning the entry module (falling back to the working directory).
    const name =
      packageName ??
      readPackageName(entryModuleId === null ? resolveCwd() : path.dirname(entryModuleId))
    if (!name) {
      throw new Error(
        `[pandacss] Unable to resolve the package name from package.json, which is required by \`exports\` for the self-referential CSS import. Disable \`exports\` (or \`inject\`) to wire up the CSS import yourself.`,
      )
    }
    return name
  }

  /**
   * Reports Panda's diagnostics as build warnings, each once: the parse of a module and its
   * transform report the same ones (the transform's without the `file`, which `defaultFile`
   * fills in so they dedupe), and every build the host runs re-scans the sources.
   */
  function warnDiagnostics(
    warn: (message: string) => void,
    diagnostics: readonly Diagnostic[] | undefined,
    context: string,
    defaultFile?: string,
  ): void {
    if (!diagnostics?.length) return
    const cwd = resolveCwd()
    for (const reported of diagnostics) {
      const diagnostic =
        reported.file === undefined && defaultFile !== undefined
          ? {...reported, file: defaultFile}
          : reported
      const key = diagnosticKey(diagnostic)
      if (reportedDiagnostics.has(key)) continue
      reportedDiagnostics.add(key)
      warn(
        `[pandacss] Panda reported ${diagnostic.severity === 'error' ? 'an error' : `a ${diagnostic.severity}`} ${context}: ${describeDiagnostic(diagnostic, cwd)}`,
      )
    }
  }

  const transformHandler: TransformHandler = function transformHandler(code, id) {
    if (!driver) return undefined
    const [filePath = id] = id.split('?')
    // `.d.ts` files can match the config's `include` globs (e.g. `src/**/*.ts`) but hold no
    // styles
    if (RE_DTS.test(filePath)) return undefined
    if (this.meta.watchMode) {
      // Every module depends on the config (and its imports): a change there can rename the
      // class names of the modules this hook rewrites, and cover modules it skipped so far.
      // Registering the files from here, per module, makes rolldown transform the modules
      // again when they change — also under `experimental.incrementalBuild`, which otherwise
      // reuses the transforms of the modules whose own files did not change — while
      // `buildStart` only makes them trigger a rebuild.
      this.addWatchFile(driver.configPath)
      for (const dependency of driver.configDependencies) {
        this.addWatchFile(driver.resolvePath(dependency))
      }
    }
    // The files the config doesn't cover aren't scanned by Panda — rewriting them would
    // produce class names the stylesheet doesn't have. A module a reloaded config no longer
    // covers stops counting as styled, too.
    if (!driver.isSourceFile(filePath)) {
      pandaModules.delete(id)
      return undefined
    }

    // Parse the module from the code rolldown hands over (which may differ from the file on
    // disk after other plugins' transforms), so the stylesheet matches the published code.
    const report = driver.compiler.parseFileSource(filePath, code)
    warnDiagnostics(
      (message) => this.warn(message),
      report.diagnostics,
      `while parsing ${displayPath(filePath, resolveCwd())}`,
      filePath,
    )
    // The module uses Panda styles when the parse extracted anything — or when it only
    // reported diagnostics: a call with a dynamic value extracts nothing (and is left to the
    // runtime below) but still produces class names the stylesheet has to be loaded for, so the
    // entry chunks reaching the module get the CSS import either way.
    let usesStyles =
      report.cssCalls + report.cvaCalls + report.svaCalls + report.jsxUsages > 0 ||
      report.diagnostics.length > 0

    let transformed: {code: string; map: string | null} | undefined
    if (transformEnabled) {
      const result = transformSource({
        transformer: resolveTransformer(driver),
        path: filePath,
        source: code,
        mode: 'build',
      })
      for (const dependency of result.dependencies) {
        this.addWatchFile(dependency)
      }
      warnDiagnostics(
        (message) => this.warn(message),
        result.diagnostics,
        `while transforming ${displayPath(filePath, resolveCwd())}`,
        filePath,
      )
      if (result.bailed) {
        this.warn(
          `[pandacss] Panda could not rewrite the style calls in "${displayPath(filePath, resolveCwd())}" — they run at runtime, so Panda's runtime is bundled into the output for them.`,
        )
      }
      usesStyles ||= result.changed || result.bailed
      if (result.changed) transformed = {code: result.code, map: result.map}
    }

    if (!usesStyles) {
      // The parse report doesn't count pattern, config recipe or `token()` calls, so a module
      // using only those looks style-free — and without the transform nothing else notices
      // them. The extraction lists every call Panda matched.
      const extracted = driver.compiler.extractFileSource(filePath, code)
      usesStyles = extracted.calls.length > 0 || extracted.jsx.length > 0
    }

    // Deleted as well as added: in watch mode a module can stop using Panda styles, and its
    // entry chunks then no longer need the CSS import
    if (usesStyles) pandaModules.add(id)
    else pandaModules.delete(id)
    return transformed
  }

  const plugin: PandacssPlugin = {
    name: 'pandacss',

    api: {
      setBuildContext(context: BuildContext): void {
        if (context.target !== undefined) contextTarget = context.target
        if (context.packageName !== undefined) packageName = context.packageName
        if (context.cwd !== undefined) contextCwd = context.cwd
        if (context.outDir !== undefined) contextOutDir = context.outDir
      },
    },

    // The Panda config is loaded here, before rolldown reads the plugin's hooks, so the
    // `transform` hook filter can be derived from the config's `include`/`exclude` globs and
    // rolldown skips the Rust ↔ JS roundtrip for every module outside them. Not in watch mode,
    // though: the filter is fixed for the session while the config (and its globs) reloads on
    // every rebuild, so only declaration files are skipped natively there and the handler
    // decides per module with the current config. `inject` also prepends the CSS import in
    // `renderChunk` through rolldown's native MagicString (`meta.magicString`), which keeps
    // sourcemaps intact without a JS magic-string dependency.
    async options(inputOptions) {
      if (inputOptions.cwd !== undefined) inputCwd = inputOptions.cwd
      const cwd = resolveCwd()
      const currentDriver = await resolveDriver(cwd)
      // Outside tsdown (whose `build:before` hook already ran it), the first codegen runs here,
      // ahead of every plugin's `buildStart`: rolldown runs those in parallel, and a
      // declaration plugin reads the generated types from its own
      if (codegenEnabled && codegenBeforeBuilds === undefined) runCodegen(currentDriver)
      const filter = this.meta.watchMode
        ? CONSERVATIVE_TRANSFORM_FILTER
        : createTransformFilter(currentDriver, cwd)
      plugin.transform = filter ? {filter, handler: transformHandler} : {handler: transformHandler}

      let nextOptions = inputOptions
      if (this.meta.watchMode) {
        // `buildStart` watches the directories the `include` globs are rooted in, so sources
        // added later are picked up. The directories this build writes to — Panda's generated
        // `styled-system`, and the output directory the host resolved — may sit inside them
        // (e.g. `include: ['./**/*.tsx']`), and every write there would trigger the next
        // rebuild: exclude them from watching.
        const excluded = [currentDriver.getOutdir(options.outdir)]
        // Real, like the watched directories, which come from the (real) project root
        if (contextOutDir !== undefined) {
          excluded.push(realpathOrSelf(path.resolve(cwd, contextOutDir)))
        }
        // `watch: false` is rolldown's way to disable watching, and nothing to add to then
        if (inputOptions.watch !== false) {
          const previous = inputOptions.watch?.exclude
          nextOptions = {
            ...nextOptions,
            watch: {
              ...inputOptions.watch,
              exclude: [
                ...(previous === undefined ? [] : Array.isArray(previous) ? previous : [previous]),
                ...excluded.map(directoryPattern),
              ],
            },
          }
        }
      }
      if (inject) {
        nextOptions = {
          ...nextOptions,
          experimental: {...nextOptions.experimental, nativeMagicString: true},
        }
      }
      return nextOptions === inputOptions ? undefined : nextOptions
    },

    // Scan every source the config covers before any module is transformed: the transformer
    // folds tokens and style objects across files, so a module's dependencies must be known
    // when it is rewritten, regardless of the order rolldown discovers modules in. The
    // stylesheet then covers the whole `include` set, like `panda cssgen` — and like
    // `@pandacss/vite`, which scans the project the same way when Vite's config is resolved.
    // The first codegen already ran (in tsdown's `build:before` hook or the `options` hook);
    // a watch rebuild regenerates after a config change, so the generated types, runtime and
    // class name hashes stay in sync with the config the stylesheet is extracted with.
    async buildStart() {
      const currentDriver = await resolveDriver(resolveCwd())
      if (built && this.meta.watchMode) {
        // A rebuild may follow a config change: reload it (which swaps the compiler when it
        // changed) so the codegen, the scan and the transforms below use the current config.
        // Panda only writes the files whose content changed, so a current directory stays
        // untouched either way.
        const {hasChanged} = await currentDriver.reload()
        if (hasChanged && codegenEnabled) runCodegen(currentDriver)
      }
      built = true

      warnDiagnostics(
        (message) => this.warn(message),
        currentDriver.designSystemDiagnostics,
        'while loading the design system',
      )
      const cwd = resolveCwd()
      for (const report of currentDriver.parseFiles()) {
        warnDiagnostics(
          (message) => this.warn(message),
          report.diagnostics,
          `while parsing ${displayPath(report.path, cwd)}`,
        )
        // The stylesheet covers every scanned source, including the ones no entry imports, so
        // each of them has to trigger a rebuild in watch mode (the imported ones are watched
        // through the module graph anyway)
        this.addWatchFile(report.path)
      }
      if (this.meta.watchMode) {
        // A source added later is only noticed when the directories the `include` globs are
        // rooted in are watched too; the next scan then decides whether it is covered. The
        // config and its imports aren't part of the module graph either.
        const targets = currentDriver.watchTargets()
        for (const dir of targets.dirs) {
          this.addWatchFile(currentDriver.resolvePath(dir))
        }
        this.addWatchFile(currentDriver.configPath)
        for (const dependency of currentDriver.configDependencies) {
          this.addWatchFile(currentDriver.resolvePath(dependency))
        }
      }
    },

    // The transformer rewrites non-static compositions (e.g. `css(base, condition && extra)`)
    // into calls of a tiny class-merging runtime it imports from a virtual module, resolved
    // and loaded here — the same virtual module `@pandacss/transformer`'s own bundler plugins
    // provide
    resolveId: {
      filter: {id: {include: [new RegExp(`^${escapeRegExp(INTERNAL_CSS_IMPORT)}$`)]}},
      handler(id) {
        return id === INTERNAL_CSS_IMPORT ? INTERNAL_CSS_RESOLVED_ID : undefined
      },
    },

    load: {
      filter: {id: {include: [new RegExp(`^${escapeRegExp(INTERNAL_CSS_RESOLVED_ID)}$`)]}},
      handler(id) {
        if (id !== INTERNAL_CSS_RESOLVED_ID) return undefined
        return {
          code: getInternalCssRuntimeSource(resolveCxSeparator(driver?.config)),
          moduleType: 'js',
        }
      },
    },

    // Replaced in the `options` hook with the filtered version once the config is known
    transform: {handler: transformHandler},

    // Inject the CSS import into entry chunks that reach Panda styles: relative by default
    // (like `css.inject` in `@tsdown/css`), or the self-referential bare specifier when the
    // CSS file is published as an export subpath
    renderChunk(code, chunk, outputOptions, meta) {
      if (!inject || pandaModules.size === 0) return undefined
      // The `.d` name / `.d.ts` file checks skip the chunks of tsdown's d.ts passes — they
      // never contain styles, so outside tsdown this is a harmless no-op guard.
      if (!chunk.isEntry || chunk.name.endsWith('.d') || RE_DTS.test(chunk.fileName))
        return undefined
      const {format} = outputOptions
      if (format !== 'es' && format !== 'cjs') return undefined
      if (!chunkHasStyles(chunk, meta.chunks, pandaModules)) return undefined

      const specifier = JSON.stringify(
        exportsCss
          ? `${resolvePackageName(chunk.facadeModuleId)}/${fileName}`
          : relativeImportPath(chunk.fileName, fileName),
      )
      // After the hashbang and the directive prologue (`"use strict"`, `"use client"`, …):
      // a statement before them would end the prologue, turning strict mode off in CJS output
      // and hiding the directives from the tools that read them
      let offset = prologueEnd(code)
      if (offset > 0) {
        // On the line after the prologue, when it ends with a line break
        if (code.startsWith('\r\n', offset)) offset += 2
        else if (code[offset] === '\n') offset += 1
      }
      const statement = `${format === 'cjs' ? `require(${specifier});` : `import ${specifier};`}\n`

      const {magicString} = meta
      if (magicString) {
        if (offset > 0) magicString.appendLeft(offset, statement)
        else magicString.prepend(statement)
        return magicString
      }
      // Fallback when another `options` hook disabled `experimental.nativeMagicString`: the
      // import is still injected, but without the native magic-string the chunk's sourcemap
      // can't be adjusted for it (rolldown reports it as SOURCEMAP_BROKEN as well).
      if (outputOptions.sourcemap) {
        this.warn(
          `[pandacss] rolldown's native magic-string is unavailable (another plugin's \`options\` hook may have disabled \`experimental.nativeMagicString\`), so the CSS import injected into "${chunk.fileName}" shifts its sourcemap by one line.`,
        )
      }
      return {code: code.slice(0, offset) + statement + code.slice(offset)}
    },

    // Emit the stylesheet (optimized with lightningcss) and, with `exports.nodeCompat`, the JS
    // shim
    generateBundle(_outputOptions, bundle) {
      if (!driver) return
      // tsdown's cjs d.ts pass renders no JS chunks, so skip it instead of re-emitting the
      // assets (a harmless no-op guard outside tsdown)
      const chunks = Object.values(bundle).filter(
        (assetOrChunk): assetOrChunk is Rolldown.OutputChunk =>
          assetOrChunk.type === 'chunk' &&
          !assetOrChunk.name.endsWith('.d') &&
          !RE_DTS.test(assetOrChunk.fileName),
      )
      if (chunks.length === 0) return

      // Every layer is requested (the sources decide which ones have content) but the
      // `@layer reset, base, …;` declaration isn't: it would declare layers the stylesheet
      // doesn't use, and ordering the layers is the consuming application's call. Panda's own
      // minification is left off in favor of lightningcss below.
      const output = driver.getLayerCss({
        layers: ALL_LAYERS,
        emitLayerDeclaration: false,
        minify: false,
        polyfill: options.polyfill ?? driver.config['polyfill'] === true,
      })
      warnDiagnostics(
        (message) => this.warn(message),
        output.diagnostics,
        'while compiling the stylesheet',
      )
      let css = output.css

      // With `exports`, the `./<fileName>` export (written into `package.json` by the host at
      // config-resolution time, before any CSS is known) must resolve, so the CSS file and its
      // shims are emitted even when no styles were extracted. Otherwise nothing references an
      // empty CSS file, so it would just be a stray artifact.
      if (!css && !exportsCss) return

      if (css) {
        css = optimizeCss(css, {
          fileName,
          minify,
          targets: resolveTargets(),
          lightningcss,
          layerNames: resolveLayerNames(driver.config),
          warn: (message) => this.warn(`[pandacss] ${message}`),
        })
      }

      this.emitFile({type: 'asset', fileName, source: css})

      if (nodeCompat) {
        // The shim is intentionally free of syntax so it parses as both CommonJS and an ES
        // module, and is named `bundle-css.js` (not `bundle.css.js`) so no CSS pipeline treats
        // it as a stylesheet module when a consumer resolves `./bundle.css`. Its declaration
        // file backs the export's `types` condition, so a separate `<css>.d.ts` for the CSS
        // file itself is unnecessary.
        this.emitFile({
          type: 'asset',
          fileName: cssShimFileName(fileName),
          source: cssShimSource(fileName),
        })
        this.emitFile({
          type: 'asset',
          fileName: cssShimDtsFileName(fileName),
          source: cssShimDtsSource(fileName),
        })
      }
    },

    // Compose into the user config before it is resolved — the tsdown analogue of a Vite plugin
    // extending the user config from its `config` hook:
    // - With `codegen`, the first codegen joins tsdown's hooks as a `build:before` hook. tsdown
    //   cleans after resolving the config (and `clean` may list the generated directory), then
    //   calls `build:before` before any build of a format starts — including the separate CJS
    //   declaration build, which runs without the user plugins and reads the generated types.
    //   It is registered ahead of the user's own hooks, so theirs see the generated files.
    // - With `exports`, write the `./<fileName>` export to `package.json` (and, through tsdown,
    //   to `publishConfig.exports`) through `exports.customExports`. tsdown's `exports` feature
    //   is opt-in, so nothing is written (and the export has to be maintained manually) when
    //   it's not enabled.
    tsdownConfig(config: UserConfig) {
      if (codegenEnabled) {
        codegenBeforeBuilds = undefined
        const userHooks = config.hooks
        config.hooks = async (hooks) => {
          // Every format calls it; the first runs the codegen, and all of them wait for it
          hooks.hook('build:before', async () => {
            codegenBeforeBuilds ??= resolveDriver(resolveCwd()).then(runCodegen)
            await codegenBeforeBuilds
          })
          if (typeof userHooks === 'function') await userHooks(hooks)
          else if (userHooks) hooks.addHooks(userHooks)
        }
      }

      if (!exportsCss) return undefined
      const exportsOption = config.exports
      if (!exportsOption) return undefined

      // Normalize the `boolean | CIOption | object` forms of the `exports` option into the
      // object form, preserving the enabled-ness (`true` and bare CI conditions mean enabled)
      const exportsOptions: ExportsOptions =
        exportsOption === true
          ? {}
          : typeof exportsOption === 'string'
            ? {enabled: exportsOption}
            : exportsOption

      const previousCustomExports = exportsOptions.customExports
      exportsOptions.customExports = async (exportsMap, context) => {
        // Apply a pre-existing `customExports` first (both its function and record forms,
        // mirroring how tsdown itself applies them), then insert the CSS export
        const base =
          typeof previousCustomExports === 'function'
            ? await previousCustomExports(exportsMap, context)
            : previousCustomExports
              ? {...exportsMap, ...previousCustomExports}
              : exportsMap
        const outDir = resolveOutDir(config, context, fileName)
        const cssExport = nodeCompat
          ? createConditionalCssExport(fileName, outDir)
          : createCssExport(fileName, outDir)
        return insertCssExport(base, `./${fileName}`, cssExport)
      }
      config.exports = exportsOptions
      return undefined
    },

    // Forward the tsdown-resolved context: the top-level `target` (the default for the CSS
    // syntax lowering target, like `css.target` in `@tsdown/css`), the package name (for the
    // self-referential import injected by `inject` with `exports`), and the working directory
    // the Panda config is discovered from. The hook fires once per output format with the
    // same values. The first codegen doesn't run here: tsdown calls it before its `clean` step.
    tsdownConfigResolved(config: ResolvedConfig) {
      plugin.api.setBuildContext({
        target: config.target,
        packageName: config.pkg?.name,
        cwd: config.cwd,
        outDir: config.outDir,
      })
    },
  }

  return plugin
}

/**
 * Derive the `transform` hook filter from the config's `include`/`exclude` globs, resolved
 * against the config's working directory so they match rolldown's absolute module ids. Without
 * either in the config there is nothing to scope by, so the hook runs for every module (and
 * decides per module); a glob the converter does not support falls back to the
 * {@link CONSERVATIVE_TRANSFORM_FILTER}, which can never reject a module Panda covers.
 */
function createTransformFilter(driver: PandaDriver, cwd: string): TransformHookFilter | undefined {
  const include = readGlobs(driver.config['include'])
  const exclude = readGlobs(driver.config['exclude'])
  if (include.length === 0 && exclude.length === 0) return undefined

  const includePatterns: RegExp[] = []
  const excludePatterns: RegExp[] = []
  for (const pattern of include) {
    // A negated include is an exclude
    const negated = pattern.startsWith('!')
    const regExp = globToRegExp(negated ? pattern.slice(1) : pattern, cwd)
    if (!regExp) return CONSERVATIVE_TRANSFORM_FILTER
    ;(negated ? excludePatterns : includePatterns).push(regExp)
  }
  for (const pattern of exclude) {
    const regExp = globToRegExp(pattern.replace(/^!/, ''), cwd)
    if (!regExp) return CONSERVATIVE_TRANSFORM_FILTER
    excludePatterns.push(regExp)
  }

  return {
    id: {
      ...(includePatterns.length > 0 ? {include: includePatterns} : {}),
      exclude: [RE_DTS, ...excludePatterns],
    },
  }
}

function readGlobs(value: unknown): string[] {
  if (typeof value === 'string') return [value]
  if (!Array.isArray(value)) return []
  return value.filter((entry): entry is string => typeof entry === 'string')
}

/**
 * Convert one of the config's source globs (relative to the config's `cwd`, e.g.
 * `./src/**\/*.css.ts`) into a RegExp over absolute module ids. A RegExp rather than rolldown's
 * glob strings because rolldown tests RegExp filters against ids with their path separators
 * normalized to `/`, which keeps the filter portable to Windows. Only the glob itself is glob
 * syntax: the directory it is resolved against is matched literally, brackets and all. The
 * syntax covered is the fast-glob subset Panda configs use — `**`, `*`, `?`, `{a,b}`
 * alternation and plain `[…]` classes; a glob using anything else (extglob groups, negated
 * classes, brace ranges, a globstar at a brace boundary, `.`/`..` segments past the leading
 * ones) returns `undefined`, so the caller can leave the native filter unscoped instead of
 * guessing.
 */
function globToRegExp(glob: string, cwd: string): RegExp | undefined {
  if (RE_UNSUPPORTED_GLOB.test(glob)) return undefined

  // Windows paths use backslashes, which fast-glob only reads as escapes: on Windows (where a
  // glob built with `path.join` or `path.resolve` has them) and in a glob starting with a
  // drive letter, they are separators like in the working directory and rolldown's ids
  let pattern =
    process.platform === 'win32' || RE_WINDOWS_DRIVE.test(glob) ? glob.replaceAll('\\', '/') : glob
  // `./` and `../` prefixes address the literal base directory, which an absolute glob replaces
  let base: string | undefined = path.resolve(cwd).replaceAll('\\', '/')
  if (pattern.startsWith('/') || RE_WINDOWS_DRIVE.test(pattern)) {
    base = undefined
  } else {
    for (;;) {
      if (pattern.startsWith('./')) {
        pattern = pattern.slice(2)
      } else if (pattern.startsWith('../')) {
        base = parentDirectory(base)
        pattern = pattern.slice(3)
      } else {
        break
      }
    }
  }
  // A `.` or `..` segment past the leading ones (`src/../lib/**/*.ts`) names a directory the
  // module ids never spell out, so a RegExp would reject files Panda's matcher covers
  if (RE_DOT_SEGMENT.test(pattern)) return undefined

  // The base ends with exactly one `/`, also when it is a root (`/`, `C:/`) — which already
  // ends with one, so that slash is dropped first
  let source = base === undefined ? '' : `${escapeRegExp(base.replace(/\/+$/, ''))}/`
  let inClass = false
  let braceDepth = 0
  for (let index = 0; index < pattern.length; index++) {
    const char = pattern[index] ?? ''
    if (inClass) {
      if (char === ']') inClass = false
      source += char
      continue
    }
    switch (char) {
      case '\\': {
        const next = pattern[index + 1]
        if (next === undefined) {
          source += '\\\\'
        } else {
          source += escapeRegExp(next)
          index++
        }
        break
      }
      case '*': {
        const previous = pattern[index - 1]
        const afterStar = pattern[index + 2]
        if (pattern[index + 1] === '*') {
          if (
            (previous === undefined || previous === '/') &&
            (afterStar === undefined || afterStar === '/')
          ) {
            // A `**` segment spans directories; `**/` also matches zero of them, so
            // `src/**/*.ts` matches `src/a.ts` like fast-glob does
            if (afterStar === '/') {
              source += '(?:.*/)?'
              index += 2
            } else {
              source += '.*'
              index += 1
            }
            break
          }
          // `**` next to a brace boundary (`{**/*.ts,…}`, `{src/**,lib}`) is a globstar whose
          // segment semantics depend on the alternative it is in — left to Panda's matcher
          if (
            previous === '{' ||
            previous === ',' ||
            afterStar === ',' ||
            afterStar === '}' ||
            (braceDepth > 0 && (previous === undefined || afterStar === undefined))
          ) {
            return undefined
          }
          // Otherwise `**` inside a segment (`a**b`) is just `*`, like fast-glob
          source += '[^/]*'
          index += 1
          break
        }
        source += '[^/]*'
        break
      }
      case '?':
        source += '[^/]'
        break
      case '[':
        inClass = true
        source += '['
        break
      case '{':
        braceDepth++
        source += '(?:'
        break
      case '}':
        if (braceDepth > 0) {
          braceDepth--
          source += ')'
        } else {
          source += '\\}'
        }
        break
      case ',':
        source += braceDepth > 0 ? '|' : ','
        break
      default:
        source += escapeRegExp(char)
    }
  }
  // An id may carry a query (`?raw` and the like), which the handler strips before asking the
  // driver. Windows paths are case-insensitive, and rolldown's ids may differ from the resolved
  // config path in the drive letter's case.
  return new RegExp(`^${source}(?:\\?.*)?$`, process.platform === 'win32' ? 'i' : '')
}

/**
 * A `watch.exclude` pattern for a directory and everything in it, matching the path with either
 * separator (rolldown hands watch paths over as the OS spells them).
 */
function directoryPattern(dir: string): RegExp {
  const segments = path
    .resolve(dir)
    .split(/[\\/]+/)
    .filter((segment) => segment !== '')
    .map(escapeRegExp)
  const prefix = path.isAbsolute(dir) && !/^[A-Za-z]:/.test(segments[0] ?? '') ? '[\\\\/]' : ''
  return new RegExp(`^${prefix}${segments.join('[\\\\/]')}(?:[\\\\/]|$)`)
}

/**
 * The real path of a file or directory, resolving symlinks in the part of the path that exists
 * (an output directory may not exist yet), or the path itself when nothing does.
 */
function realpathOrSelf(file: string): string {
  try {
    return fs.realpathSync(file)
  } catch {
    const parent = path.dirname(file)
    return parent === file ? file : path.join(realpathOrSelf(parent), path.basename(file))
  }
}

/** The parent of a POSIX-form directory, stopping at the filesystem root (`/`, `C:`). */
function parentDirectory(dir: string): string {
  if (RE_FS_ROOT.test(dir)) return dir
  const parent = path.posix.dirname(dir)
  return parent === '.' ? dir : parent
}

/**
 * The build's output directory relative to the root of the package whose `package.json` the
 * exports are written to (POSIX separators, `''` for the root itself). tsdown resolves `outDir`
 * against its `cwd`, and the directory can be absolute or `./`-prefixed, so it is never used
 * as written: `customExports` runs after the build, when the emitted CSS asset carries the
 * resolved output directory; the config's `outDir` resolved against `cwd` is the fallback.
 */
function resolveOutDir(
  config: UserConfig,
  context: CustomExportsContext,
  cssFileName: string,
): string {
  // tsdown always resolves the package with its path here — its own exports generation reads
  // `packageJsonPath` unconditionally from the same object — only the declared context type is
  // the plain `PackageJson` shape
  const pkg: Partial<PackageJsonWithPath> = context.pkg
  const cwd = config.cwd ?? process.cwd()
  const pkgRoot = pkg.packageJsonPath ? path.dirname(pkg.packageJsonPath) : cwd
  let outDir: string | undefined
  for (const chunks of Object.values(context.chunks)) {
    const asset = chunks?.find(
      (chunk) => chunk.type === 'asset' && chunk.fileName.replaceAll('\\', '/') === cssFileName,
    )
    if (asset) {
      outDir = asset.outDir
      break
    }
  }
  outDir ??= path.resolve(cwd, config.outDir ?? 'dist')
  return path.relative(pkgRoot, outDir).replaceAll('\\', '/')
}

/** The layer names of a Panda config: the defaults, with the config's `layers` renames applied. */
function resolveLayerNames(config: PandaDriver['config']): Set<string> {
  const names = new Set<string>(ALL_LAYERS)
  const renames = config['layers']
  if (typeof renames === 'object' && renames !== null) {
    for (const name of Object.values(renames)) {
      if (typeof name === 'string') names.add(name)
    }
  }
  return names
}

interface OptimizeCssOptions {
  fileName: string
  minify: boolean
  targets: Targets | undefined
  lightningcss: LightningCSSOptions | undefined
  layerNames: ReadonlySet<string>
  warn: (message: string) => void
}

/**
 * Run the stylesheet through lightningcss: syntax lowering to the targets, the removal of the
 * `--made-with-panda` marker (and whatever else `unusedSymbols` names) and of the rules and
 * layers that leaves empty, and minification when enabled.
 */
function optimizeCss(css: string, optimizeOptions: OptimizeCssOptions): string {
  const {fileName, minify, targets, lightningcss, layerNames, warn} = optimizeOptions

  // The spread order matches `@tsdown/css`: the plugin-managed fields (`targets` from the
  // resolved `target`, `minify`, `cssModules`, which Panda's own class naming makes redundant,
  // and the `unusedSymbols` the marker is prepended to) win over their `lightningcss`
  // counterparts
  const result = transform({
    filename: fileName,
    code: new TextEncoder().encode(css),
    ...lightningcss,
    unusedSymbols: [MADE_WITH_PANDA_SYMBOL, ...(lightningcss?.unusedSymbols ?? [])],
    minify,
    cssModules: false,
    targets,
  })
  for (const warning of result.warnings) {
    warn(`${warning.message} (${warning.loc.filename}:${warning.loc.line})`)
  }
  let optimized = new TextDecoder().decode(result.code)

  // A layer the optimization empties (`base`, once the marker is gone) survives as a
  // `@layer base;` statement: lightningcss keeps it because an empty layer block still orders
  // the cascade. The layer holds no rules of the library's, though, so it is exactly the kind
  // of declaration `emitLayerDeclaration: false` leaves to the consuming application — strip
  // the statements of Panda's layers in a second pass (the first one's visitors already ran,
  // so only this plugin's runs here).
  if (RE_LAYER_STATEMENT.test(optimized)) {
    const stripped = transform({
      filename: fileName,
      code: new TextEncoder().encode(optimized),
      ...lightningcss,
      visitor: {
        Rule: {
          'layer-statement'(rule) {
            const names = rule.value.names
            return names.every((name) => name.length === 1 && layerNames.has(name[0] ?? ''))
              ? []
              : undefined
          },
        },
      },
      unusedSymbols: undefined,
      minify,
      cssModules: false,
      targets,
    })
    optimized = new TextDecoder().decode(stripped.code)
  }

  if (optimized.length && !optimized.endsWith('\n')) optimized += '\n'
  return optimized
}

function diagnosticKey(diagnostic: Diagnostic): string {
  const {code, severity, file, message} = diagnostic
  const line = diagnostic.location?.start.line ?? diagnostic.span?.start ?? ''
  const column = diagnostic.location?.start.column ?? ''
  return `${severity}|${code}|${file ?? ''}|${line}|${column}|${message}`
}

function describeDiagnostic(diagnostic: Diagnostic, cwd: string): string {
  let text = diagnostic.message
  if (diagnostic.file) {
    const location = diagnostic.location
      ? `:${diagnostic.location.start.line}:${diagnostic.location.start.column}`
      : ''
    text += ` (${displayPath(diagnostic.file, cwd)}${location})`
  }
  if (diagnostic.help?.length) {
    text += `\n  ${diagnostic.help.join('\n  ')}`
  }
  return text
}

/** A path relative to the working directory when it is inside it, for messages. */
function displayPath(filePath: string, cwd: string): string {
  if (!path.isAbsolute(filePath)) return filePath
  const relativePath = path.relative(cwd, filePath)
  return relativePath && !relativePath.startsWith('..') ? relativePath : filePath
}

/** The `name` of the closest `package.json` at or above a directory. */
function readPackageName(startDir: string): string | undefined {
  let dir = path.resolve(startDir)
  for (;;) {
    const packageJsonPath = path.join(dir, 'package.json')
    if (fs.existsSync(packageJsonPath)) {
      try {
        const pkg: unknown = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'))
        if (typeof pkg === 'object' && pkg !== null && 'name' in pkg) {
          const {name} = pkg
          if (typeof name === 'string' && name) return name
        }
      } catch {
        // A malformed package.json is skipped, like a nameless one
      }
    }
    const parent = path.dirname(dir)
    if (parent === dir) return undefined
    dir = parent
  }
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

/**
 * The offset right after a chunk's hashbang and directive prologue — where a statement can be
 * inserted without ending the prologue — or `0` when the chunk has neither.
 */
function prologueEnd(code: string): number {
  let offset = RE_HASHBANG.exec(code)?.[0].length ?? 0
  for (;;) {
    const directive = RE_DIRECTIVE.exec(code.slice(offset))
    if (!directive) return offset
    offset += directive[0].length
  }
}

/**
 * The relative import path from a chunk to the emitted CSS file (which lives at the root of the
 * output directory), like the `css.inject` implementation in `@tsdown/css`.
 */
function relativeImportPath(chunkFileName: string, cssFileName: string): string {
  const relativePath = path.posix.relative(path.posix.dirname(chunkFileName), cssFileName)
  // Only `./` and `../` make a specifier relative: `.assets/bundle.css` would name a package
  return relativePath.startsWith('../') ? relativePath : `./${relativePath}`
}

/**
 * The `fileName` option as the emitted file's path inside the output directory: POSIX
 * separators and no `./` prefix, so `./bundle.css` publishes the `./bundle.css` export subpath
 * rather than `././bundle.css`. A path outside the output directory is rejected, since neither
 * the export nor the injected import could address it.
 */
function normalizeFileName(fileName: string): string {
  const normalized = path.posix.normalize(fileName.replaceAll('\\', '/'))
  if (
    normalized === '.' ||
    normalized.endsWith('/') ||
    normalized === '..' ||
    normalized.startsWith('../') ||
    path.posix.isAbsolute(normalized) ||
    RE_WINDOWS_DRIVE.test(normalized)
  ) {
    throw new Error(
      `[pandacss] \`fileName\` must name a file inside the output directory, like "bundle.css" or "assets/bundle.css", but got "${fileName}".`,
    )
  }
  return normalized
}

/**
 * Whether a chunk (or any chunk it imports, transitively) contains a module with Panda styles.
 */
function chunkHasStyles(
  chunk: Rolldown.RenderedChunk,
  chunks: Record<string, Rolldown.RenderedChunk>,
  styledModules: ReadonlySet<string>,
): boolean {
  const seen = new Set<string>()
  const queue: Rolldown.RenderedChunk[] = [chunk]
  for (let current = queue.pop(); current; current = queue.pop()) {
    if (seen.has(current.fileName)) continue
    seen.add(current.fileName)
    if (current.moduleIds.some((id) => styledModules.has(id))) return true
    for (const imported of [...current.imports, ...current.dynamicImports]) {
      const importedChunk = chunks[imported]
      if (importedChunk) queue.push(importedChunk)
    }
  }
  return false
}

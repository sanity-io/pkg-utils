/**
 * Every cascade layer Panda can emit, in cascade order. A library build cannot know ahead of
 * time which layers its sources end up using (recipes, global CSS and keyframes land in
 * different ones), so the stylesheet is always requested for all of them — Panda omits the
 * empty ones, and lightningcss removes the ones the optimization empties.
 */
const ALL_LAYERS: StylesheetLayerName[] = ['reset', 'base', 'tokens', 'recipes', 'utilities']

/** Matches rendered `.d.ts`/`.d.mts`/`.d.cts` chunk file names and module ids. */
const RE_DTS = /\.d\.[cm]?ts$/

/**
 * Matches the glob syntax {@link globToRegExp} leaves to Panda's own matcher: extglob groups
 * (`@(ts|tsx)`, `+(…)`, `!(…)`, …), negated classes (`[!a]`, `[^a]`) and brace ranges (`{1..3}`).
 */
const RE_UNSUPPORTED_GLOB = /[?*+@!]\(|\[[!^]|\{[^{}]*\.\.[^{}]*\}/

/** Matches a `.` or `..` path segment of a (POSIX-form) glob. */
const RE_DOT_SEGMENT = /(?:^|\/)\.\.?(?:\/|$)/

/** Matches a Windows drive at the start of a glob (`C:/…` or `C:\…`), i.e. an absolute pattern. */
const RE_WINDOWS_DRIVE = /^[A-Za-z]:[\\/]/

/** Matches a filesystem root in POSIX form: `/`, or a Windows drive like `C:` or `C:/`. */
const RE_FS_ROOT = /^(?:[A-Za-z]:)?\/?$/

/** Matches a `@layer <names>;` statement (as opposed to a `@layer <name> { … }` block). */
const RE_LAYER_STATEMENT = /@layer\s+[^{};]+;/

/** Matches the hashbang line a chunk may start with. */
const RE_HASHBANG = /^#![^\n]*\n?/

/**
 * Matches one directive of a chunk's prologue — a string-literal expression statement such as
 * `"use strict";` or `'use client'` — together with the whitespace and comments before it.
 */
const RE_DIRECTIVE =
  /^(?:\s|\/\/[^\n]*\n|\/\*[\s\S]*?\*\/)*(?:"(?:[^"\\\n]|\\.)*"|'(?:[^'\\\n]|\\.)*')[^\S\n]*(?:;|(?=\r?\n)|$)/

/**
 * Options for {@link pandacssPlugin}: the options of the official `@pandacss/vite` plugin for
 * locating the Panda config, plus the CSS output options modeled after the `css` options of
 * [`@tsdown/css`](https://tsdown.dev/options/css) (the same vocabulary as
 * `@sanity/vanilla-extract-tsdown-plugin`) so they feel familiar in a tsdown-based toolchain.
 * @public
 */
export interface Options {
  /**
   * The project root the Panda config is discovered from (`panda.config.ts` upward), and the
   * directory its `include`/`exclude` globs are relative to — like `cwd` in `@pandacss/vite`.
   * A relative path is resolved against tsdown's `cwd` (or rolldown's, outside tsdown).
   * @defaultValue tsdown's resolved `cwd` (the directory of the `tsdown.config.ts`)
   */
  cwd?: string
  /**
   * An explicit Panda config file, relative to {@link Options.cwd | `cwd`}, instead of
   * discovering it upward — like `configPath` in `@pandacss/vite`.
   */
  configPath?: string
  /**
   * Run Panda's codegen before the build starts (and again after a config change in watch
   * mode), writing the `styled-system` artifacts of the loaded config before any module is
   * transformed — like `@pandacss/vite` does when Vite's config is resolved. The generated
   * types, runtime and class name hashes the sources import then match the config the
   * stylesheet is extracted with, even when the package's `prepare` script (`panda codegen`)
   * ran against an older config. Under tsdown it runs once for the builds of every format,
   * after tsdown's `clean` step, so `clean` may list the generated directory. Panda only
   * writes the files whose content changed, so current artifacts stay untouched.
   *
   * Set to `false` when codegen is managed elsewhere.
   * @defaultValue true
   */
  codegen?: boolean
  /**
   * Where the codegen artifacts are written, relative to {@link Options.cwd | `cwd`} — like
   * `outdir` in `@pandacss/vite`.
   * @defaultValue the `outdir` of the Panda config
   */
  outdir?: string
  /**
   * Rewrite the `css()`, `cva()`, pattern and recipe calls of the modules Panda's `include`
   * globs cover into static class name strings with `@pandacss/transformer`, so the published
   * JavaScript neither bundles nor imports Panda's runtime (`styled-system/css`, …) — the same
   * rewrite as `transform: true` in `@pandacss/vite`, which defaults to `false` there because
   * applications keep the runtime around. A call the transformer cannot resolve statically is
   * left as is (with a warning) and keeps importing the runtime.
   *
   * Set to `false` to only extract the CSS; the modules then keep their runtime calls, and the
   * runtime is bundled into the output through the package's `imports` map.
   * @defaultValue true
   */
  transform?: boolean
  /**
   * Emit the extracted CSS without cascade layers (Panda's `@layer` polyfill), for browsers
   * that predate `@layer`.
   * @defaultValue the `polyfill` option of the Panda config
   */
  polyfill?: boolean
  /**
   * Name of the emitted CSS file that the extracted CSS is written to, like `css.fileName`
   * in `@tsdown/css` (which defaults to `"style.css"`).
   * @defaultValue "bundle.css"
   */
  fileName?: string
  /**
   * Minify the extracted CSS with `lightningcss`, matching `css.minify` in `@tsdown/css`. The
   * CSS always goes through `lightningcss`, so empty rules and layers, and the
   * {@link MADE_WITH_PANDA_SYMBOL | `--made-with-panda`} marker, are removed regardless.
   * @defaultValue false
   */
  minify?: boolean
  /**
   * The target environment for CSS syntax lowering. Accepts esbuild-style target strings
   * (e.g. `'chrome90'`, `'safari16.2'`), like `css.target` in `@tsdown/css`. Set to `false`
   * to disable syntax lowering entirely.
   *
   * Defaults to tsdown's resolved top-level `target`, forwarded through
   * {@link PandacssPluginApi.setBuildContext} from the plugin's `tsdownConfigResolved` hook.
   * Matching `@tsdown/css`, syntax lowering is skipped when no target is configured anywhere,
   * or when the configured targets don't include any browsers (e.g. `'node20'`, which speaks to
   * the JS runtime, not the browsers the extracted CSS runs in). `@sanity/tsdown-config` layers
   * its own default on top, resolving browserless targets from `@sanity/browserslist-config`
   * and passing them through {@link Options.lightningcss | `lightningcss.targets`}.
   */
  target?: string | string[] | false
  /**
   * Options passed through to `lightningcss`'s `transform()`, like `css.lightningcss` in
   * `@tsdown/css`. `lightningcss.targets` takes precedence over the esbuild-style
   * {@link Options.target | `target`}, and `lightningcss.unusedSymbols` extends the
   * {@link MADE_WITH_PANDA_SYMBOL | `--made-with-panda`} entry the plugin always removes.
   */
  lightningcss?: LightningCSSOptions
  /**
   * Inject an import of the extracted CSS file into every entry chunk that reaches a module
   * with Panda styles, like `css.inject` in `@tsdown/css` (and matching its default of
   * `false`), so bundler-consumed libraries load their CSS automatically. In CJS output it is
   * a `require()` instead of an `import`.
   *
   * The injected specifier depends on {@link Options.exports | `exports`}: a relative
   * `import "./<fileName>"` on its own, or the self-referential `"<pkg-name>/<fileName>"` bare
   * specifier when the CSS file is published as an export subpath.
   *
   * `@sanity/tsdown-config` defaults this to `true`.
   * @defaultValue false
   */
  inject?: boolean
  /**
   * Publish the extracted CSS file as the `"./<fileName>"` export subpath of the package, so
   * consumers can `import "<pkg-name>/<fileName>"` — which is also the specifier
   * {@link Options.inject | `inject`} then uses, instead of a relative path.
   *
   * - `true` declares a plain `"./<fileName>": "./<outDir>/<fileName>"` export. Enough for
   *   packages that only ever run in browsers or bundlers.
   * - `{nodeCompat: true}` declares a conditional export instead, whose `browser`/`style`
   *   conditions point at the stylesheet while `node`/`default` point at a no-op JS shim (e.g.
   *   `bundle-css.js`) emitted next to it, with a `bundle-css.d.ts` declaration for the
   *   export's `types` condition. That keeps the subpath resolvable in runtimes that cannot
   *   load `.css` files.
   *
   * The export is written to `package.json` (and, through tsdown, to `publishConfig.exports`)
   * through tsdown's [`exports` feature](https://tsdown.dev/options/package-exports) when
   * it's enabled; otherwise it has to be maintained by hand.
   *
   * `@sanity/tsdown-config` defaults this to `{nodeCompat: true}`.
   * @defaultValue false
   */
  exports?: boolean | CssExportsOptions
}

